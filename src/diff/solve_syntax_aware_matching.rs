/// Phase 4: syntax-aware subtree matching. Named-group matching and positional anchoring
/// (`solve_greedy_anchor_blocks`) share one engine, `grouped_greedy_matcher::solve`, with
/// different candidate predicates, keys and costs; the import passes reuse it too.
///
/// `solve_large_flat_subtrees` runs first: a huge flat literal nested deep inside a named item
/// would otherwise be swallowed by that item's whole-subtree APTED call, where the flat-tree fast
/// path never sees it (c-cpython-autogenerated-code).
pub fn solve(ctx: &PassCtx, diff: &mut ASTDiff) {
    let (before, after) = (ctx.before, ctx.after);
    solve_large_flat_subtrees::solve(ctx, diff);
    solve_qualified_name_groups(before, after, diff);
    solve_import_list_overlap(before, after, diff);
    solve_import_path_similarity(before, after, diff);
    solve_greedy_anchor_blocks::solve(ctx, diff);
}

/// Matches `nodes::is_semantically_structural` candidates by `(kind, fully-resolved name)`, where
/// the name is scope-qualified by every enclosing named node (`"Bar::new"`, not `"new"`), so the
/// qualification disambiguates methods of different impls for every kind uniformly. Groups hold
/// several ids to support N:M (overloads, duplicate impls).
///
/// No rejection threshold: a shared qualified name already *is* the identity signal, even for a
/// fully rewritten body, so cost (`solve_greedy_anchor_blocks::cost_ratio`) only breaks ties within
/// a group. Runs before positional anchoring so identity beats position.
///
/// The members of an accepted pair that have no name counterpart go through
/// [`resolve_orphan_members`] before the pair's APTED call, which would otherwise pair them by slot.
fn solve_qualified_name_groups(before: &Code, after: &Code, diff: &mut ASTDiff) {
    let before_metadata = metadata_of(before);
    let after_metadata = metadata_of(after);
    let language = before_metadata.language;

    let Some(before_root) = before.ast.as_ref().map(|ast| ast.root_node()) else {
        return;
    };
    let Some(after_root) = after.ast.as_ref().map(|ast| ast.root_node()) else {
        return;
    };

    let before_groups = collect_qualified_name_groups(before_root, &language, before);
    let after_groups = collect_qualified_name_groups(after_root, &language, after);

    match_qualified_name_groups(
        before_groups,
        after_groups,
        &before_metadata,
        &after_metadata,
        diff,
    );
}

/// [`solve_qualified_name_groups`] scoped to an already-matched `(before_root, after_root)` pair,
/// matching only nested content, never the roots themselves.
///
/// For `solve_large_flat_subtrees`, which runs before the whole-file name pass and would otherwise
/// leave named content next to a large flat literal (Go `t.Run` subtests) to unconstrained APTED.
// Every parameter is distinct context; a params struct would only relocate them.
#[allow(clippy::too_many_arguments)]
pub(crate) fn solve_qualified_name_groups_within(
    before_root: Node,
    before_root_id: usize,
    after_root: Node,
    after_root_id: usize,
    before_metadata: &crate::code::ASTMetadata,
    after_metadata: &crate::code::ASTMetadata,
    before_code: &Code,
    after_code: &Code,
    diff: &mut ASTDiff,
) {
    let language = before_metadata.language;

    let before_groups = collect_qualified_name_groups_excluding_root(
        before_root,
        before_root_id,
        &language,
        before_code,
    );
    let after_groups = collect_qualified_name_groups_excluding_root(
        after_root,
        after_root_id,
        &language,
        after_code,
    );

    match_qualified_name_groups(
        before_groups,
        after_groups,
        before_metadata,
        after_metadata,
        diff,
    );
}

/// Flattens one side's groups into one candidate list in `preorder_index` order, which
/// `grouped_greedy_matcher` needs for determinism (`HashMap` key order is not deterministic).
fn flatten_and_sort_candidates(
    groups: HashMap<(String, String), Vec<usize>>,
    metadata: &crate::code::ASTMetadata,
) -> Vec<(usize, (String, String))> {
    let mut candidates: Vec<(usize, (String, String))> = groups
        .into_iter()
        .flat_map(|(key, ids)| ids.into_iter().map(move |id| (id, key.clone())))
        .collect();
    candidates.sort_by_key(|(id, _)| {
        metadata
            .node_info
            .get(id)
            .map(|i| i.preorder_index)
            .unwrap_or(usize::MAX)
    });
    candidates
}

fn match_qualified_name_groups(
    before_groups: HashMap<(String, String), Vec<usize>>,
    after_groups: HashMap<(String, String), Vec<usize>>,
    before_metadata: &crate::code::ASTMetadata,
    after_metadata: &crate::code::ASTMetadata,
    diff: &mut ASTDiff,
) {
    let before_orphans = collect_orphan_members(&before_groups, &after_groups, before_metadata);
    let after_orphans = collect_orphan_members(&after_groups, &before_groups, after_metadata);
    let before_candidates = flatten_and_sort_candidates(before_groups, before_metadata);
    let after_candidates = flatten_and_sort_candidates(after_groups, after_metadata);

    grouped_greedy_matcher::solve(
        diff,
        &before_candidates,
        &after_candidates,
        |before_id, after_id| {
            solve_greedy_anchor_blocks::cost_ratio(
                before_id,
                after_id,
                before_metadata,
                after_metadata,
            )
            .unwrap_or(0.0)
        },
        None,
        |before_id, after_id, diff| {
            resolve_orphan_members(
                before_id,
                after_id,
                &before_orphans,
                &after_orphans,
                before_metadata,
                after_metadata,
                diff,
            );
            // The statement and local pre-matches only emit exact, scoped matches, so they narrow
            // the APTED call below without changing what it would resolve. The if-clause one
            // does change it: a swap is the one edit ordered APTED cannot express.
            apted::prematch_identical_statement_siblings(
                before_id,
                after_id,
                before_metadata,
                after_metadata,
                "qualified_name",
                diff,
            );
            apted::prematch_identical_if_clauses(
                before_id,
                after_id,
                before_metadata,
                after_metadata,
                "qualified_name",
                diff,
            );
            apted::prematch_unique_named_locals(
                before_id,
                after_id,
                before_metadata,
                after_metadata,
                "unique_named_local",
                diff,
            );
            apted::for_nodes(
                before_metadata,
                after_metadata,
                vec![before_id],
                vec![after_id],
                Algorithm::Apted,
                "qualified_name",
                diff,
            );
        },
    );
}

/// A named member that owns a body (function, method, class, impl; not a field or an import)
/// whose `(kind, qualified name)` has no counterpart on the other side: renamed, or removed (or
/// added) outright.
struct OrphanMember {
    id: usize,
    kind: String,
    /// The nearest enclosing candidate whose key the other side also has: two orphans are compared
    /// only within the same scope.
    scope: (String, String),
    /// The name without its qualification or a Kotlin signature (`getActivities(Long)`).
    bare_name: String,
}

/// The orphan members of one side, outermost only (an orphan inside another goes with it), in
/// preorder. One with no enclosing matched-by-name scope is never inside an accepted pair, so it
/// is left out.
fn collect_orphan_members(
    groups: &HashMap<(String, String), Vec<usize>>,
    other_groups: &HashMap<(String, String), Vec<usize>>,
    metadata: &crate::code::ASTMetadata,
) -> Vec<OrphanMember> {
    let language = metadata.language;
    let key_of: HashMap<usize, &(String, String)> = groups
        .iter()
        .flat_map(|(key, ids)| ids.iter().map(move |&id| (id, key)))
        .collect();
    let mut orphans = Vec::new();
    for (key, ids) in groups {
        if other_groups.contains_key(key) {
            continue;
        }
        for &id in ids {
            let Some(info) = metadata.node_info.get(&id) else {
                continue;
            };
            // A field is one line whose rename reads as an edit; a body is what APTED pairs
            // statement by statement into unrelated code.
            if !nodes::is_reference(&info.kind, &language)
                || nodes::is_import_kind(&info.kind, &language)
                || info.kind == "field_declaration"
            {
                continue;
            }
            let mut scope = None;
            let mut node = id;
            while let Some(&parent) = metadata.node_to_parent.get(&node) {
                if let Some(parent_key) = key_of.get(&parent) {
                    if other_groups.contains_key(*parent_key) {
                        scope = Some((*parent_key).clone());
                    }
                    // Either the scope, or an enclosing orphan that this one goes with.
                    break;
                }
                node = parent;
            }
            let Some(scope) = scope else {
                continue;
            };
            let unqualified = key.1.rsplit("::").next().unwrap_or(&key.1);
            let bare_name = unqualified
                .split('(')
                .next()
                .unwrap_or(unqualified)
                .to_string();
            orphans.push(OrphanMember {
                id,
                kind: info.kind.clone(),
                scope,
                bare_name,
            });
        }
    }
    orphans.sort_by_key(|orphan| {
        metadata
            .node_info
            .get(&orphan.id)
            .map(|i| i.preorder_index)
            .unwrap_or(usize::MAX)
    });
    orphans
}

/// Whether `ancestor` is a strict ancestor of `id`.
fn is_strict_descendant(
    mut id: usize,
    ancestor: usize,
    metadata: &crate::code::ASTMetadata,
) -> bool {
    while let Some(&parent) = metadata.node_to_parent.get(&id) {
        if parent == ancestor {
            return true;
        }
        id = parent;
    }
    false
}

/// The orphan-member gate, run inside an accepted name pair before its whole-pair APTED call.
///
/// Unit-cost APTED pairs same-shaped constructs for free (same-kind internal nodes cost nothing),
/// so a removed method and an added one in the same slot come out paired leaf by leaf, keywords
/// and punctuation included, though they share no name and no statement
/// (`java-defects4j-jxpath-7-*`). Within one scope, an orphan that has same-kind orphans on the
/// other side pairs with the one of the same bare name when that name is unique on both sides,
/// else with its strict mutual best by [`apted::entry_similarity`] at or above
/// [`apted::SEGMENT_MUTUAL_SIMILARITY_MIN`] (every renamed method in the ground truth scores 0.56
/// or more; the jxpath replacements 0.25 or less), each pair through its own APTED call. The rest
/// of those are deleted or inserted whole, which leaves them to phase 7 to move if they only
/// moved. An orphan with no same-kind rival is left to the pair's APTED call, as before.
#[allow(clippy::too_many_arguments)]
fn resolve_orphan_members(
    before_id: usize,
    after_id: usize,
    before_orphans: &[OrphanMember],
    after_orphans: &[OrphanMember],
    before_metadata: &crate::code::ASTMetadata,
    after_metadata: &crate::code::ASTMetadata,
    diff: &mut ASTDiff,
) {
    let inside = |orphans: &'_ [OrphanMember],
                  root: usize,
                  metadata: &crate::code::ASTMetadata,
                  node_map: &rustc_hash::FxHashMap<usize, usize>|
     -> Vec<usize> {
        (0..orphans.len())
            .filter(|&i| {
                !node_map.contains_key(&orphans[i].id)
                    && is_strict_descendant(orphans[i].id, root, metadata)
            })
            .collect()
    };
    let before_inside = inside(
        before_orphans,
        before_id,
        before_metadata,
        &diff.before_node_map,
    );
    let after_inside = inside(
        after_orphans,
        after_id,
        after_metadata,
        &diff.after_node_map,
    );
    // Only an orphan with a same-kind rival in its scope on the other side is the gate's business.
    // A lone new method may be built from leftovers around it (comments, statements) that the
    // pair's APTED call carries in (`java-defects4j-cli-13-writeablecommandlineimpl`).
    let contested = |own: &OrphanMember, others: &[OrphanMember], indices: &[usize]| {
        indices
            .iter()
            .any(|&i| others[i].scope == own.scope && others[i].kind == own.kind)
    };
    let before_inside: Vec<usize> = before_inside
        .iter()
        .copied()
        .filter(|&bi| contested(&before_orphans[bi], after_orphans, &after_inside))
        .collect();
    let after_inside: Vec<usize> = after_inside
        .iter()
        .copied()
        .filter(|&ai| contested(&after_orphans[ai], before_orphans, &before_inside))
        .collect();
    if before_inside.is_empty() && after_inside.is_empty() {
        return;
    }

    let mut pairs: Vec<(usize, usize)> = Vec::new();
    let mut paired_before: HashSet<usize> = HashSet::new();
    let mut paired_after: HashSet<usize> = HashSet::new();
    for &bi in &before_inside {
        let b = &before_orphans[bi];
        let same_name = |orphans: &'_ [OrphanMember], indices: &[usize], name: &str| {
            indices
                .iter()
                .copied()
                .filter(|&i| {
                    orphans[i].scope == b.scope
                        && orphans[i].kind == b.kind
                        && orphans[i].bare_name == name
                })
                .collect::<Vec<usize>>()
        };
        let rivals = same_name(before_orphans, &before_inside, &b.bare_name);
        let partners = same_name(after_orphans, &after_inside, &b.bare_name);
        if rivals.len() == 1 && partners.len() == 1 {
            pairs.push((bi, partners[0]));
            paired_before.insert(bi);
            paired_after.insert(partners[0]);
        }
    }

    let similarity = |bi: usize, ai: usize| -> f32 {
        let (b, a) = (&before_orphans[bi], &after_orphans[ai]);
        if b.scope != a.scope || b.kind != a.kind {
            return 0.0;
        }
        apted::entry_similarity(before_metadata, b.id, after_metadata, a.id)
    };
    let open_before: Vec<usize> = before_inside
        .iter()
        .copied()
        .filter(|bi| !paired_before.contains(bi))
        .collect();
    let open_after: Vec<usize> = after_inside
        .iter()
        .copied()
        .filter(|ai| !paired_after.contains(ai))
        .collect();
    let scores: Vec<Vec<f32>> = open_before
        .iter()
        .map(|&bi| open_after.iter().map(|&ai| similarity(bi, ai)).collect())
        .collect();
    // The single best at or above the floor; a tie disqualifies.
    let strict_best = |values: &mut dyn Iterator<Item = f32>| -> Option<usize> {
        let mut best: Option<(usize, f32)> = None;
        let mut tied = false;
        for (i, v) in values.enumerate() {
            match best {
                Some((_, bv)) if v > bv => {
                    best = Some((i, v));
                    tied = false;
                }
                Some((_, bv)) if v == bv => tied = true,
                None => best = Some((i, v)),
                _ => {}
            }
        }
        match best {
            Some((i, v)) if !tied && v >= apted::SEGMENT_MUTUAL_SIMILARITY_MIN => Some(i),
            _ => None,
        }
    };
    for (row, &bi) in open_before.iter().enumerate() {
        let Some(col) = strict_best(&mut scores[row].iter().copied()) else {
            continue;
        };
        if strict_best(&mut scores.iter().map(|r| r[col])) == Some(row) {
            pairs.push((bi, open_after[col]));
            paired_before.insert(bi);
            paired_after.insert(open_after[col]);
        }
    }

    for (bi, ai) in pairs {
        apted::for_nodes(
            before_metadata,
            after_metadata,
            vec![before_orphans[bi].id],
            vec![after_orphans[ai].id],
            Algorithm::Apted,
            "qualified_name",
            diff,
        );
    }
    for &bi in &before_inside {
        if !paired_before.contains(&bi) {
            apted::add_delete_mappings(
                before_orphans[bi].id,
                before_metadata,
                "qualified_name",
                diff,
            );
        }
    }
    for &ai in &after_inside {
        if !paired_after.contains(&ai) {
            apted::add_insert_mappings(
                after_orphans[ai].id,
                after_metadata,
                "qualified_name",
                diff,
            );
        }
    }
}

/// Only nodes `nodes::is_semantically_structural` names push onto the scope, so unnamed wrappers
/// (`declaration_list`, a class `block`) do not appear in qualified names.
fn collect_qualified_name_groups(
    root: Node,
    language: &Language,
    code: &Code,
) -> HashMap<(String, String), Vec<usize>> {
    let mut out = HashMap::new();
    let mut scope: Vec<String> = Vec::new();
    collect_qualified_name_groups_rec(root, language, code, &mut scope, &mut out);
    out
}

/// [`collect_qualified_name_groups`] without `root_id` itself; the root still qualifies its
/// children's names (`"TestThings::<subtest>"`).
fn collect_qualified_name_groups_excluding_root(
    root: Node,
    root_id: usize,
    language: &Language,
    code: &Code,
) -> HashMap<(String, String), Vec<usize>> {
    let mut groups = collect_qualified_name_groups(root, language, code);
    for ids in groups.values_mut() {
        ids.retain(|&id| id != root_id);
    }
    groups.retain(|_, ids| !ids.is_empty());
    groups
}

fn collect_qualified_name_groups_rec(
    node: Node,
    language: &Language,
    code: &Code,
    scope: &mut Vec<String>,
    out: &mut HashMap<(String, String), Vec<usize>>,
) {
    let mut pushed_scope = false;
    if let Some((kind, name)) = nodes::is_semantically_structural(&node, language, code) {
        let full_name = if scope.is_empty() {
            name.clone()
        } else {
            format!("{}::{}", scope.join("::"), name)
        };
        out.entry((kind, full_name)).or_default().push(node.id());
        scope.push(name);
        pushed_scope = true;
    }

    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        collect_qualified_name_groups_rec(child, language, code, scope, out);
    }

    if pushed_scope {
        scope.pop();
    }
}

/// Minimum Jaccard overlap of imported-symbol sets for [`solve_import_list_overlap`].
const IMPORT_LIST_SIMILARITY_THRESHOLD: f64 = 0.5;

/// Pairs unmapped Rust `use foo::{a, b, c}` statements with the same base path by Jaccard overlap
/// of their symbol sets; a changed symbol set defeats phase 1's hash match and there is no other
/// identity signal.
///
/// Matches whole statements, never single list members: a member matched in isolation fragments
/// the list's comma assignment, which APTED gets right only with the whole list in view.
fn solve_import_list_overlap(before: &Code, after: &Code, diff: &mut ASTDiff) {
    let before_metadata = metadata_of(before);
    let after_metadata = metadata_of(after);
    if before_metadata.language != Language::Rust {
        return;
    }

    let Some(before_root) = before.ast.as_ref().map(|ast| ast.root_node()) else {
        return;
    };
    let Some(after_root) = after.ast.as_ref().map(|ast| ast.root_node()) else {
        return;
    };

    let before_items =
        collect_rust_grouped_use_declarations(before_root, before, &diff.before_node_map);
    let after_items =
        collect_rust_grouped_use_declarations(after_root, after, &diff.after_node_map);
    if before_items.is_empty() || after_items.is_empty() {
        return;
    }

    let before_candidates: Vec<(usize, String)> = before_items
        .iter()
        .map(|(id, path, _)| (*id, path.clone()))
        .collect();
    let after_candidates: Vec<(usize, String)> = after_items
        .iter()
        .map(|(id, path, _)| (*id, path.clone()))
        .collect();
    let before_symbols: HashMap<usize, &HashSet<&str>> = before_items
        .iter()
        .map(|(id, _, symbols)| (*id, symbols))
        .collect();
    let after_symbols: HashMap<usize, &HashSet<&str>> = after_items
        .iter()
        .map(|(id, _, symbols)| (*id, symbols))
        .collect();

    grouped_greedy_matcher::solve(
        diff,
        &before_candidates,
        &after_candidates,
        |before_id, after_id| {
            1.0 - flow_control_similarity_of_sets(
                before_symbols[&before_id],
                after_symbols[&after_id],
            )
        },
        Some(1.0 - IMPORT_LIST_SIMILARITY_THRESHOLD),
        |before_id, after_id, diff| {
            apted::for_nodes(
                &before_metadata,
                &after_metadata,
                vec![before_id],
                vec![after_id],
                Algorithm::Apted,
                "import_list_overlap",
                diff,
            );
        },
    );
}

/// Jaccard floor for [`solve_import_path_similarity`].
const IMPORT_PATH_SIMILARITY_THRESHOLD: f64 = 0.5;

/// Fewest shared path tokens a pair needs: one shared top-level directory is no evidence.
const IMPORT_PATH_MIN_SHARED_TOKENS: usize = 2;

/// Differing-token budget, `1 + union / IMPORT_PATH_TOKEN_BUDGET_DIVISOR`. An absolute count, not a
/// ratio: on a three-token path every difference is a third of it, yet one changed token is a path
/// edit and two is another file. The length term keeps a long Java path's two-segment relocation
/// acceptable (kotlin-nextcloud-android-move-from-one-mocking-library-to-other pins the rejection).
const IMPORT_PATH_TOKEN_BUDGET_DIVISOR: usize = 6;

/// Pairs unmapped import statements (any language [`nodes::is_import_kind`] knows) by Jaccard over
/// their path tokens, bucketed by node kind. A pair must also pass
/// [`import_paths_are_the_same_module`] and [`import_paths_have_no_rival`]; otherwise it is
/// priced out, not ranked low. Statement-level only, as in [`solve_import_list_overlap`].
fn solve_import_path_similarity(before: &Code, after: &Code, diff: &mut ASTDiff) {
    let before_metadata = metadata_of(before);
    let after_metadata = metadata_of(after);
    let language = before_metadata.language;
    if language != after_metadata.language {
        return;
    }

    let Some(before_root) = before.ast.as_ref().map(|ast| ast.root_node()) else {
        return;
    };
    let Some(after_root) = after.ast.as_ref().map(|ast| ast.root_node()) else {
        return;
    };

    let before_items =
        collect_unmapped_imports(before_root, before, &diff.before_node_map, &language);
    let after_items = collect_unmapped_imports(after_root, after, &diff.after_node_map, &language);
    if before_items.is_empty() || after_items.is_empty() {
        return;
    }

    let candidates =
        |items: &[(usize, &'static str, HashSet<&str>)]| -> Vec<(usize, &'static str)> {
            items.iter().map(|(id, kind, _)| (*id, *kind)).collect()
        };
    let before_candidates = candidates(&before_items);
    let after_candidates = candidates(&after_items);
    let before_tokens: HashMap<usize, &HashSet<&str>> = before_items
        .iter()
        .map(|(id, _, tokens)| (*id, tokens))
        .collect();
    let after_tokens: HashMap<usize, &HashSet<&str>> = after_items
        .iter()
        .map(|(id, _, tokens)| (*id, tokens))
        .collect();

    grouped_greedy_matcher::solve(
        diff,
        &before_candidates,
        &after_candidates,
        |before_id, after_id| {
            let (before_set, after_set) = (before_tokens[&before_id], after_tokens[&after_id]);
            if !import_paths_are_the_same_module(before_set, after_set)
                || !import_paths_have_no_rival(before_set, after_set, &before_items, &after_items)
            {
                // The matcher has one `max_cost` for all pairs; these rules are per-pair.
                return f64::INFINITY;
            }
            1.0 - flow_control_similarity_of_sets(before_set, after_set)
        },
        Some(1.0 - IMPORT_PATH_SIMILARITY_THRESHOLD),
        |before_id, after_id, diff| {
            apted::for_nodes(
                &before_metadata,
                &after_metadata,
                vec![before_id],
                vec![after_id],
                Algorithm::Apted,
                "import_path_similarity",
                diff,
            );
        },
    );
}

/// Whether two token sets name the same module: enough shared tokens, and few enough differing
/// ones to read as a path edit.
fn import_paths_are_the_same_module(before: &HashSet<&str>, after: &HashSet<&str>) -> bool {
    let shared = before.intersection(after).count();
    let union = before.union(after).count();
    let differing = union - shared;
    shared >= IMPORT_PATH_MIN_SHARED_TOKENS
        && differing <= 1 + union / IMPORT_PATH_TOKEN_BUDGET_DIVISOR
}

/// Whether this pair is the *only* acceptable reading on both sides. N:1 import edits (a split
/// import, eight imports collapsed into a `*`) leave every group member acceptable, and a greedy
/// 1:1 pick orphans the rest; such group edits are left to APTED, which sees the whole block
/// (scala-com-lihaoyi-mill-split-import).
fn import_paths_have_no_rival(
    before: &HashSet<&str>,
    after: &HashSet<&str>,
    before_items: &[(usize, &'static str, HashSet<&str>)],
    after_items: &[(usize, &'static str, HashSet<&str>)],
) -> bool {
    let rivals_for = |set: &HashSet<&str>, items: &[(usize, &'static str, HashSet<&str>)]| {
        items
            .iter()
            .filter(|(_, _, other)| import_paths_are_the_same_module(set, other))
            .count()
    };
    rivals_for(before, after_items) == 1 && rivals_for(after, before_items) == 1
}

/// Language keywords dropped before scoring; kept, they lift every pair in a file by a fixed
/// amount. Matched case-insensitively against whole tokens only.
const IMPORT_KEYWORD_TOKENS: &[&str] = &[
    "import", "include", "use", "using", "from", "require", "package",
];

/// Every unmapped import statement as `(node id, node kind, alphanumeric tokens)`. The kind is the
/// matcher's bucket key, so C++'s `preproc_include` and `using_declaration` never compete.
fn collect_unmapped_imports<'a>(
    root: Node<'a>,
    code: &'a Code,
    mapped: &rustc_hash::FxHashMap<usize, usize>,
    language: &Language,
) -> Vec<(usize, &'static str, HashSet<&'a str>)> {
    let bytes = code.contents.as_bytes();
    let mut out = Vec::new();
    let mut stack = vec![root];
    while let Some(node) = stack.pop() {
        if nodes::is_import_kind(node.kind(), language) {
            if !mapped.contains_key(&node.id())
                && let Ok(text) = node.utf8_text(bytes)
            {
                let tokens: HashSet<&str> = text
                    .split(|c: char| !c.is_alphanumeric())
                    .filter(|token| {
                        !token.is_empty()
                            && !IMPORT_KEYWORD_TOKENS
                                .iter()
                                .any(|keyword| token.eq_ignore_ascii_case(keyword))
                    })
                    .collect();
                if !tokens.is_empty() {
                    out.push((node.id(), node.kind(), tokens));
                }
            }
            continue;
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            stack.push(child);
        }
    }
    out
}

/// `(id, base path, symbol set)` for every unmapped `use foo::{a, b, ...}`; single-symbol imports
/// have nothing to score.
fn collect_rust_grouped_use_declarations<'a>(
    root: Node<'a>,
    code: &'a Code,
    mapped: &rustc_hash::FxHashMap<usize, usize>,
) -> Vec<(usize, String, HashSet<&'a str>)> {
    let bytes = code.contents.as_bytes();
    let mut out = Vec::new();
    let mut stack = vec![root];
    while let Some(node) = stack.pop() {
        if node.kind() == "use_declaration" && !mapped.contains_key(&node.id()) {
            if let Some(scoped_use_list) = node.child_by_field_name("argument")
                && scoped_use_list.kind() == "scoped_use_list"
                && let Some(path_node) = scoped_use_list.child_by_field_name("path")
                && let Some(list_node) = scoped_use_list.child_by_field_name("list")
                && list_node.kind() == "use_list"
                && let Ok(path_text) = path_node.utf8_text(bytes)
            {
                let mut symbols = HashSet::new();
                let mut cursor = list_node.walk();
                for child in list_node.named_children(&mut cursor) {
                    if let Ok(text) = child.utf8_text(bytes) {
                        symbols.insert(text);
                    }
                }
                if !symbols.is_empty() {
                    out.push((node.id(), path_text.to_string(), symbols));
                }
            }
            continue;
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            stack.push(child);
        }
    }
    out
}

